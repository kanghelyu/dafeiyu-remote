validate_port() {
  local name="$1" value="$2" allow_empty="${3:-0}"
  if [ "$allow_empty" = 1 ] && [ -z "$value" ]; then return 0; fi
  [[ "$value" =~ ^[0-9]{1,5}$ ]] || die "$name must be a port in 1..65535"
  [ "$value" -ge 1 ] && [ "$value" -le 65535 ] || die "$name must be in 1..65535"
}

validate_admin() {
  local value="$1"
  [[ "$value" =~ ^(127\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}|\[::1\]):[0-9]{1,5}$ ]] \
    || die "admin address must be a loopback IP:port (127.0.0.1:21119 or [::1]:21119)"
  validate_port "admin port" "${value##*:}"
  if [[ "$value" =~ ^127\. ]]; then
    local ip="${value%:*}" octet
    local -a octets
    IFS=. read -r -a octets <<< "$ip"
    for octet in "${octets[@]}"; do
      [ "$octet" -le 255 ] || die "invalid admin IPv4 address"
    done
  fi
}

validate_number() {
  local name="$1" value="$2" kind="$3"
  if [ "$kind" = int ]; then
    [[ "$value" =~ ^[0-9]+$ ]] && [ "$value" -ge 1 ] || die "$name must be an integer >= 1"
  else
    [[ "$value" =~ ^[0-9]+([.][0-9]+)?$ ]] || die "$name must be a non-negative number"
    if [ "$kind" = positive ]; then
      [[ "$value" =~ [1-9] ]] || die "$name must be greater than 0"
    fi
  fi
}

validate_args() {
  [[ "$REPO_OWNER" =~ ^[A-Za-z0-9_.-]+$ ]] || die "invalid DFY_REPO_OWNER"
  [[ "$REPO_NAME" =~ ^[A-Za-z0-9_.-]+$ ]] || die "invalid DFY_REPO_NAME"
  if [ "$VERSION" != latest ]; then
    [[ "$VERSION" =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-[A-Za-z0-9.-]+)?(\+[A-Za-z0-9.-]+)?$ ]] \
      || die "version must be latest or a tag such as v0.1.0"
  fi
  validate_port "relay port" "$RELAY_PORT"
  validate_port "TCP port" "$RELAY_TCP_PORT" 1
  validate_admin "$ADMIN_ADDR"
  validate_number "max sessions" "$MAX_SESSIONS" int
  validate_number "per-tag Mbps" "$PER_TAG_MBPS" nonnegative
  validate_number "tag TTL hours" "$TAG_TTL_HOURS" positive
  local path
  for path in "$PREFIX" "$CONFIG_DIR" "$SYSTEMD_DIR" "$OS_RELEASE_FILE"; do
    [[ "$path" =~ ^/[A-Za-z0-9_./+-]+$ ]] || die "install paths must be absolute, not /, and contain only letters, digits, _, ., /, + or -: $path"
    case "$path" in
      /|*/|*//*|*/../*|*/./*|*/.|*/..) die "install paths must be canonical absolute paths without /, trailing slash, //, . or ..: $path" ;;
    esac
  done
  [[ "${DFY_HEALTH_RETRIES:-10}" =~ ^[0-9]+$ ]] || die "DFY_HEALTH_RETRIES must be an integer"
  [ "${DFY_HEALTH_RETRIES:-10}" -ge 1 ] || die "DFY_HEALTH_RETRIES must be >= 1"
  [[ "${DFY_HEALTH_INTERVAL:-1}" =~ ^[0-9]+$ ]] || die "DFY_HEALTH_INTERVAL must be an integer"
  [[ -z "${DFY_CARGO_TARGET_DIR:-}" || "$DFY_CARGO_TARGET_DIR" = /* ]] || die "DFY_CARGO_TARGET_DIR must be an absolute path"
  for flag in DFY_REQUIRE_CHECKSUM DFY_NO_FIREWALL DFY_PURGE_CONFIG; do
    [[ "${!flag:-0}" =~ ^[01]$ ]] || die "$flag must be 0 or 1"
  done
  if [ "$UNINSTALL" = 1 ] && [ "${DFY_PURGE_CONFIG:-0}" = 1 ]; then
    case "$CONFIG_DIR" in /etc/dfy-relay|/usr/local/etc/dfy-relay) ;; *) die "refusing to purge unexpected DFY_CONFIG_DIR: $CONFIG_DIR" ;; esac
  fi
}


while [ "$#" -gt 0 ]; do
  case "$1" in
    --from-source) FROM_SOURCE=1; shift ;;
    --yes|-y) YES=1; shift ;;
    --uninstall) UNINSTALL=1; shift ;;
    -h|--help) usage; exit 0 ;;
    --version|--relay-port|--tcp-port|--admin-addr|--max-sessions|--per-tag-mbps|--tag-ttl-hours)
      [ "$#" -ge 2 ] || die "$1 requires a value"
      case "$1" in
        --version) VERSION="$2" ;;
        --relay-port) RELAY_PORT="$2"; EXPLICIT_RELAY_PORT=1 ;;
        --tcp-port) RELAY_TCP_PORT="$2"; EXPLICIT_TCP_PORT=1 ;;
        --admin-addr) ADMIN_ADDR="$2"; EXPLICIT_ADMIN=1 ;;
        --max-sessions|--per-tag-mbps|--tag-ttl-hours)
          case "$1" in
            --max-sessions) MAX_SESSIONS="$2"; EXPLICIT_MAX_SESSIONS=1 ;;
            --per-tag-mbps) PER_TAG_MBPS="$2"; EXPLICIT_PER_TAG_MBPS=1 ;;
            --tag-ttl-hours) TAG_TTL_HOURS="$2"; EXPLICIT_TAG_TTL_HOURS=1 ;;
          esac ;;
      esac
      shift 2 ;;
    *) die "unknown argument: $1 (use --help)" ;;
  esac
done

