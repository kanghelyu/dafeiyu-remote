open_firewall() {
  [ "${DFY_NO_FIREWALL:-0}" = 1 ] && return 0
  local udp tcp
  udp="$(read_toml_string bind "$CONFIG_DIR/relay.toml" || true)"
  tcp="$(read_toml_string tcp_bind "$CONFIG_DIR/relay.toml" || true)"
  [ -n "$udp" ] && udp="${udp##*:}"
  [ -n "$tcp" ] && tcp="${tcp##*:}"
  if command -v ufw >/dev/null && ufw status 2>/dev/null | grep -q 'Status: active'; then
    ufw allow "${udp}/udp" >/dev/null || warn "could not update ufw"
    [ -z "$tcp" ] || ufw allow "${tcp}/tcp" >/dev/null || warn "could not update ufw"
  elif command -v firewall-cmd >/dev/null && firewall-cmd --state >/dev/null 2>&1; then
    firewall-cmd --permanent --add-port="${udp}/udp" >/dev/null || warn "could not update firewalld"
    [ -z "$tcp" ] || firewall-cmd --permanent --add-port="${tcp}/tcp" >/dev/null || warn "could not update firewalld"
    firewall-cmd --reload >/dev/null || warn "could not reload firewalld"
  fi
}

health_check() {
  local admin url body i retries="${DFY_HEALTH_RETRIES:-10}" interval="${DFY_HEALTH_INTERVAL:-1}"
  admin="$(read_toml_string admin_addr "$CONFIG_DIR/relay.toml" || true)"
  [ -n "$admin" ] || { warn "admin_addr is empty; installer requires /healthz"; return 1; }
  validate_admin "$admin"
  url="http://${admin}/healthz"
  log "checking $url"
  for ((i=1; i<=retries; i++)); do
    if body="$(curl --noproxy '*' -fsS --max-time 3 "$url" 2>/dev/null)" && [[ "$body" == *ok* ]]; then
      log "relay health check passed"
      return 0
    fi
    sleep "$interval"
  done
  warn "health check failed after $i attempts; inspect: journalctl -u $SERVICE_NAME -n 50 --no-pager"
  return 1
}

rollback() {
  [ "$ROLLBACK_DONE" = 0 ] || return 0
  ROLLBACK_DONE=1
  warn "rolling back failed relay installation"
  systemctl stop "$SERVICE_NAME" >/dev/null 2>&1 || true
  if [ -n "$ROLLBACK_BIN" ] && [ -f "$ROLLBACK_BIN" ]; then
    install -m 0755 "$ROLLBACK_BIN" "$PREFIX/dfy-relay"
  else
    rm -f -- "$PREFIX/dfy-relay"
  fi
  if [ "$CONFIG_EXISTED" = 1 ] && [ -f "$WORK_DIR/relay.toml.backup" ]; then
    cp -p -- "$WORK_DIR/relay.toml.backup" "$CONFIG_DIR/relay.toml" || warn "could not restore previous configuration"
  else
    rm -f -- "$CONFIG_DIR/relay.toml"
  fi
  if [ "$UNIT_EXISTED" = 1 ] && [ -f "$WORK_DIR/dfy-relay.service.backup" ]; then
    cp -p -- "$WORK_DIR/dfy-relay.service.backup" "$SYSTEMD_DIR/$SERVICE_NAME" || warn "could not restore previous systemd unit"
  else
    rm -f -- "$SYSTEMD_DIR/$SERVICE_NAME"
  fi
  systemctl daemon-reload >/dev/null 2>&1 || true
  if [ "$UNIT_EXISTED" = 1 ]; then
    if [ "$SERVICE_WAS_ENABLED" = 1 ]; then
      systemctl enable "$SERVICE_NAME" >/dev/null 2>&1 || true
    else
      systemctl disable "$SERVICE_NAME" >/dev/null 2>&1 || true
    fi
  else
    systemctl disable "$SERVICE_NAME" >/dev/null 2>&1 || true
  fi
  if [ "$SERVICE_WAS_ACTIVE" = 1 ]; then
    systemctl restart "$SERVICE_NAME" >/dev/null 2>&1 || warn "could not restart previous relay version"
  fi
}

do_install() {
  local binary config="$CONFIG_DIR/relay.toml"
  check_os
  install_deps
  if [ "$FROM_SOURCE" = 1 ]; then install_from_source; else install_from_release; fi
  binary="$(cat "$WORK_DIR/binary-path")"
  [ -x "$binary" ] || die "staged dfy-relay is missing"
  ensure_service_user
  systemctl is-active --quiet "$SERVICE_NAME" && SERVICE_WAS_ACTIVE=1
  systemctl is-enabled --quiet "$SERVICE_NAME" && SERVICE_WAS_ENABLED=1
  backup_installation
  INSTALL_MUTATED=1
  write_config "$binary"
  atomic_install_binary "$binary"
  write_service
  if [ "$SERVICE_WAS_ACTIVE" = 1 ] || ! systemctl is-active --quiet "$SERVICE_NAME"; then
    systemctl restart "$SERVICE_NAME" || die "systemd failed to restart $SERVICE_NAME"
  fi
  health_check || die "relay installation failed its health check"
  open_firewall
  local admin key udp
  admin="$(read_toml_string admin_addr "$config")"
  key="$(read_toml_string relay_key "$config" || true)"
  udp="$(read_toml_string bind "$config")"
  log "installed successfully"
  printf 'Config: %s (mode 0640, group dfy-relay)\n' "$config"
  printf 'Admin: http://%s/status\n' "$admin"
  printf 'Client relay address: %s (replace 0.0.0.0 with this host IP)\n' "$udp"
  if [ -n "$key" ]; then printf 'Client relay_key: %s\n' "$key"; else printf 'Client relay_key: read key_file referenced by %s\n' "$config"; fi
}

check_os() {
  [ -f "$OS_RELEASE_FILE" ] || die "cannot identify system ($OS_RELEASE_FILE is missing)"
  # shellcheck disable=SC1091
  . "$OS_RELEASE_FILE"
  log "system: ${PRETTY_NAME:-$ID}"
  command -v systemctl >/dev/null || die "systemd is required"
}

do_uninstall() {
  need_root
  command -v systemctl >/dev/null || die "systemd is required for uninstall"
  systemctl stop "$SERVICE_NAME" >/dev/null 2>&1 || true
  systemctl disable "$SERVICE_NAME" >/dev/null 2>&1 || true
  rm -f -- "$SYSTEMD_DIR/$SERVICE_NAME"
  systemctl daemon-reload
  rm -f -- "$PREFIX/dfy-relay"
  if [ "${DFY_PURGE_CONFIG:-0}" = 1 ]; then
    case "$CONFIG_DIR" in /etc/dfy-relay|/usr/local/etc/dfy-relay) ;; *) die "refusing to purge unexpected DFY_CONFIG_DIR: $CONFIG_DIR" ;; esac
    rm -rf -- "$CONFIG_DIR"
    log "removed $CONFIG_DIR (explicit purge requested)"
  else
    log "uninstalled; configuration preserved at $CONFIG_DIR"
  fi
}

main() {
  need_root
  if [ "$UNINSTALL" = 1 ]; then do_uninstall; return; fi
  do_install
}

main
