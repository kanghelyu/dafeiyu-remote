need_root() { [ "$(id -u)" = 0 ] || die "run as root (for example: sudo bash $0)"; }
detect_arch() {
  case "$(uname -m)" in
    x86_64|amd64) printf 'x86_64\n' ;;
    aarch64|arm64) printf 'aarch64\n' ;;
    *) die "unsupported architecture: $(uname -m)" ;;
  esac
}

install_deps() {
  command -v curl >/dev/null && command -v tar >/dev/null && command -v sha256sum >/dev/null \
    && command -v systemctl >/dev/null && return 0
  log "installing curl, tar, coreutils and systemd"
  if command -v apt-get >/dev/null; then
    DEBIAN_FRONTEND=noninteractive apt-get update
    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends curl tar coreutils systemd ca-certificates
  elif command -v dnf >/dev/null; then
    dnf install -y curl tar coreutils systemd ca-certificates
  elif command -v yum >/dev/null; then
    yum install -y curl tar coreutils systemd ca-certificates
  elif command -v apk >/dev/null; then
    apk add --no-cache curl tar coreutils systemd ca-certificates
  else
    die "install curl, tar, sha256sum and systemd manually"
  fi
}

install_from_source() {
  command -v git >/dev/null || die "--from-source requires git"
  command -v cargo >/dev/null || die "--from-source requires cargo; install Rust manually first"
  WORK_DIR="$(mktemp -d)"
  local src="$WORK_DIR/src" target_dir
  if [ "$VERSION" = latest ]; then
    git clone --depth 1 "https://github.com/${REPO_OWNER}/${REPO_NAME}.git" "$src"
  else
    git clone --depth 1 --branch "$VERSION" "https://github.com/${REPO_OWNER}/${REPO_NAME}.git" "$src"
  fi
  target_dir="${DFY_CARGO_TARGET_DIR:-$src/target}"
  ( cd "$src" && CARGO_TARGET_DIR="$target_dir" cargo build --release --locked -p dfy-relay )
  [ -x "$target_dir/release/dfy-relay" ] || die "cargo did not produce dfy-relay"
  printf '%s\n' "$target_dir/release/dfy-relay" > "$WORK_DIR/binary-path"
}

verify_checksum() {
  local archive="$1" expected_file="$2" artifact_name="$3" expected actual filename
  expected="$(awk 'NF { print $1; exit }' "$expected_file")"
  filename="$(awk 'NF { $1=""; sub(/^[* ]+/, ""); print; exit }' "$expected_file")"
  [[ "$expected" =~ ^[[:xdigit:]]{64}$ ]] || die "malformed checksum in $expected_file"
  if [ -n "$filename" ]; then
    [ "$(basename "$filename")" = "$artifact_name" ] || die "checksum is for a different artifact"
  fi
  actual="$(sha256sum "$archive")"
  [ "${actual%% *}" = "${expected,,}" ] || die "SHA-256 mismatch for $(basename "$archive")"
  log "SHA-256 verified"
}

install_from_release() {
  local arch base url tmp_checksum
  arch="$(detect_arch)"
  if [ -n "${DFY_RELEASE_BASE_URL:-}" ]; then
    base="${DFY_RELEASE_BASE_URL%/}"
  elif [ "$VERSION" = latest ]; then
    base="https://github.com/${REPO_OWNER}/${REPO_NAME}/releases/latest/download"
  else
    base="https://github.com/${REPO_OWNER}/${REPO_NAME}/releases/download/${VERSION}"
  fi
  [[ "$base" = https://* ]] || die "DFY_RELEASE_BASE_URL must use HTTPS"
  url="${DFY_ARCHIVE_URL:-$base/dfy-relay-linux-${arch}.tar.gz}"
  [[ "$url" = https://* ]] || die "DFY_ARCHIVE_URL must use HTTPS"
  if [ -n "${DFY_ARCHIVE_URL:-}" ] && [ -z "${DFY_RELEASE_BASE_URL:-}" ]; then
    base="${url%/*}"
  fi
  WORK_DIR="$(mktemp -d)"
  local archive="$WORK_DIR/relay.tar.gz"
  log "downloading $url"
  curl --proto '=https' --tlsv1.2 -fL --retry 3 --connect-timeout 15 -o "$archive" "$url" \
    || die "release download failed; use --from-source or DFY_ARCHIVE_URL for a mirror"

  # Prefer the per-artifact sidecar, then the release-wide SHA256SUMS.txt.
  if curl --proto '=https' --tlsv1.2 -fsSL --connect-timeout 10 -o "$WORK_DIR/archive.sha256" "${url}.sha256"; then
    verify_checksum "$archive" "$WORK_DIR/archive.sha256" "$(basename "$url")"
  elif curl --proto '=https' --tlsv1.2 -fsSL --connect-timeout 10 -o "$WORK_DIR/SHA256SUMS.txt" "$base/SHA256SUMS.txt"; then
    tmp_checksum="$WORK_DIR/selected.sha256"
    awk -v name="$(basename "$url")" '$2 == name || $2 == ("*" name) { print; found=1; exit } END { exit !found }' \
      "$WORK_DIR/SHA256SUMS.txt" > "$tmp_checksum"
    [ -s "$tmp_checksum" ] || die "SHA256SUMS.txt does not contain $(basename "$url")"
    verify_checksum "$archive" "$tmp_checksum" "$(basename "$url")"
  elif [ "${DFY_REQUIRE_CHECKSUM:-1}" = 1 ]; then
    die "no SHA256SUMS/sidecar available and DFY_REQUIRE_CHECKSUM=1"
  else
    warn "checksum verification explicitly disabled by DFY_REQUIRE_CHECKSUM=0"
  fi

  # Extract exactly one known member; reject absolute/traversing archive paths.
  tar -tzf "$archive" > "$WORK_DIR/members"
  awk '/^\// || /(^|\/)\.\.(\/|$)/ { bad=1 } END { exit bad }' "$WORK_DIR/members" \
    || die "archive contains unsafe paths"
  mapfile -t relay_members < <(grep -E '^(\./)?dfy-relay$' "$WORK_DIR/members" || true)
  [ "${#relay_members[@]}" -eq 1 ] || die "archive must contain exactly one dfy-relay member"
  tar -tvzf "$archive" | awk -v expected="${relay_members[0]}" '$1 ~ /^-/ && $NF == expected { found++ } END { exit found != 1 }' \
    || die "dfy-relay archive member must be a regular file"
  tar -xzf "$archive" -C "$WORK_DIR" -- "${relay_members[0]}"
  [ -x "$WORK_DIR/dfy-relay" ] || die "dfy-relay in archive is not executable"
  printf '%s\n' "$WORK_DIR/dfy-relay" > "$WORK_DIR/binary-path"
}

ensure_service_user() {
  if ! command -v getent >/dev/null || ! getent group dfy-relay >/dev/null; then
    if command -v groupadd >/dev/null; then groupadd --system dfy-relay
    elif command -v addgroup >/dev/null; then addgroup -S dfy-relay
    else die "cannot create dfy-relay group"; fi
  fi
  if ! command -v getent >/dev/null || ! getent passwd dfy-relay >/dev/null; then
    if command -v useradd >/dev/null; then
      useradd --system --gid dfy-relay --home-dir /nonexistent --shell /usr/sbin/nologin dfy-relay
    elif command -v adduser >/dev/null; then
      adduser -S -D -H -G dfy-relay dfy-relay
    else die "cannot create dfy-relay user"; fi
  fi
}

read_toml_string() {
  local key="$1" file="$2" line in_table=0
  while IFS= read -r line || [ -n "$line" ]; do
    if [[ "$line" =~ ^[[:space:]]*\[ ]]; then in_table=1; continue; fi
    [ "$in_table" = 0 ] || continue
    if [[ "$line" =~ ^[[:space:]]*${key}[[:space:]]*=[[:space:]]*\"([^\"]*)\" ]]; then
      printf '%s\n' "${BASH_REMATCH[1]}"
      return 0
    elif [[ "$line" =~ ^[[:space:]]*${key}[[:space:]]*=[[:space:]]*\'([^\']*)\' ]]; then
      printf '%s\n' "${BASH_REMATCH[1]}"
      return 0
    fi
  done < "$file"
  return 1
}

apply_config_overrides() {
  local config="$1"; shift
  command -v python3 >/dev/null || die "explicit config overrides on an existing file require Python 3.11+"
  python3 - "$config" "$@" <<'PY'
import ipaddress
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import tomllib

path = Path(sys.argv[1])
values = {}
for item in sys.argv[2:]:
    key, raw = item.split("=", 1)
    values[key] = raw
original = path.read_text(encoding="utf-8")
before = tomllib.loads(original)
# Only the prefix before the first TOML table contains top-level fields.
table = re.search(r"(?m)^[ \t]*\[", original)
prefix = original[:table.start()] if table else original
suffix = original[table.start():] if table else ""
missing = []
encoded_values = {}
for key, raw in values.items():
    encoded = json.dumps(raw) if key in {"bind", "tcp_bind", "admin_addr"} else raw
    encoded_values[key] = encoded
    pattern = re.compile(rf"(?m)^([ \t]*){re.escape(key)}[ \t]*=.*$")
    matches = list(pattern.finditer(prefix))
    if len(matches) > 1:
        raise SystemExit(f"duplicate top-level config field: {key}")
    if matches:
        match = matches[0]
        replacement = f'{match.group(1)}{key} = {encoded}'
        prefix = prefix[:match.start()] + replacement + prefix[match.end():]
    else:
        missing.append(key)
if missing:
    if prefix and not prefix.endswith("\n"):
        prefix += "\n"
    prefix += "".join(f"{key} = {encoded_values[key]}\n" for key in missing) + "\n"
original = prefix + suffix
after = tomllib.loads(original)
for key, value in before.items():
    if key not in values and after.get(key) != value:
        raise SystemExit(f"refusing to alter unrelated config field: {key}")
if "admin_addr" in values:
    addr = after["admin_addr"]
    if addr:
        ip = ipaddress.ip_address(addr.rsplit(":", 1)[0].strip("[]"))
        if not ip.is_loopback:
            raise SystemExit("admin_addr must remain loopback")
metadata = path.stat()
mode = metadata.st_mode & 0o777
fd, temporary = tempfile.mkstemp(prefix=".relay.toml.", dir=path.parent)
try:
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        stream.write(original)
        stream.flush()
        os.fsync(stream.fileno())
    os.chmod(temporary, mode)
    if hasattr(os, "chown"):
        os.chown(temporary, metadata.st_uid, metadata.st_gid)
    os.replace(temporary, path)
finally:
    if os.path.exists(temporary):
        os.unlink(temporary)
PY
}

write_config() {
  local binary="$1" overrides=() config="$CONFIG_DIR/relay.toml"
  install -d -m 0750 "$CONFIG_DIR"
  if [ ! -f "$config" ]; then
    log "generating $config with a random relay_key"
    local new="$CONFIG_DIR/.relay.toml.new.$$"
    CONFIG_NEW="$new"
    if [ -z "$RELAY_TCP_PORT" ]; then
      "$binary" config init --out "$new" --bind "0.0.0.0:$RELAY_PORT" --no-tcp --admin "$ADMIN_ADDR" >/dev/null
    else
      "$binary" config init --out "$new" --bind "0.0.0.0:$RELAY_PORT" --tcp-bind "0.0.0.0:$RELAY_TCP_PORT" --admin "$ADMIN_ADDR" >/dev/null
    fi
    chmod 0600 "$new"
    mv -f -- "$new" "$config"
    CONFIG_NEW=""
  else
    log "preserving existing $config"
  fi
  [ "$EXPLICIT_RELAY_PORT" = 1 ] && overrides+=("bind=0.0.0.0:$RELAY_PORT")
  [ "$EXPLICIT_TCP_PORT" = 1 ] && overrides+=("tcp_bind=$([ -z "$RELAY_TCP_PORT" ] && printf '' || printf '0.0.0.0:%s' "$RELAY_TCP_PORT")")
  [ "$EXPLICIT_ADMIN" = 1 ] && overrides+=("admin_addr=$ADMIN_ADDR")
  [ "$EXPLICIT_MAX_SESSIONS" = 1 ] && overrides+=("max_sessions=$MAX_SESSIONS")
  [ "$EXPLICIT_PER_TAG_MBPS" = 1 ] && overrides+=("per_tag_mbps=$PER_TAG_MBPS")
  [ "$EXPLICIT_TAG_TTL_HOURS" = 1 ] && overrides+=("tag_ttl_hours=$TAG_TTL_HOURS")
  if [ "${#overrides[@]}" -gt 0 ]; then
    log "applying explicit configuration overrides atomically"
    apply_config_overrides "$config" "${overrides[@]}"
  fi
  chgrp dfy-relay "$config"
  chmod 0640 "$config"
  "$binary" config check --config "$config" >/dev/null || die "configuration validation failed"
}

backup_installation() {
  if [ -f "$CONFIG_DIR/relay.toml" ]; then
    cp -p -- "$CONFIG_DIR/relay.toml" "$WORK_DIR/relay.toml.backup"
    CONFIG_EXISTED=1
  fi
  if [ -f "$SYSTEMD_DIR/$SERVICE_NAME" ]; then
    cp -p -- "$SYSTEMD_DIR/$SERVICE_NAME" "$WORK_DIR/dfy-relay.service.backup"
    UNIT_EXISTED=1
  fi
  if [ -f "$PREFIX/dfy-relay" ]; then
    ROLLBACK_BIN="$(mktemp "$PREFIX/.dfy-relay.backup.XXXXXX")"
    cp -p -- "$PREFIX/dfy-relay" "$ROLLBACK_BIN"
  fi
}

atomic_install_binary() {
  local source="$1" destination="$PREFIX/dfy-relay" temporary
  install -d -m 0755 "$PREFIX"
  temporary="$(mktemp "$PREFIX/.dfy-relay.new.XXXXXX")"
  install -m 0755 "$source" "$temporary"
  mv -f -- "$temporary" "$destination"
}

