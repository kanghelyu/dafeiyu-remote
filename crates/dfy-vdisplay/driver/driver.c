/*
 * driver.c - Dafeiyu virtual display driver skeleton (UMDF 2 / IddCx 1.2).
 *
 * STATUS: skeleton.  Control plane (device, interface, IOCTLs, protocol) and the
 * lifecycle of monitors and swap-chain workers are written; the pixel path and the
 * mode-description callbacks are TODO.  This file has not been compiled against a
 * WDK yet; see ../README.md for the bring-up plan and the exact API caveats.
 *
 * Hard rules enforced by the design (see ../README.md §8):
 *  - Never block inside an EvtIddCx* callback.  The swap-chain loop runs on its own
 *    thread; AssignSwapChain only creates state and starts it.
 *  - The worker thread is the only owner of IDDCX_SWAPCHAIN and deletes it on exit.
 *  - Every WDFREQUEST is completed exactly once, on every path.
 *
 * The protocol structs and IOCTL numbers live in driver.h and are mirrored in
 * crates/dfy-vdisplay/src/win_driver.rs.
 */

#include "driver.h"

#include "driver.tmh" /* generated by the WDK WPP preprocessor at build time */

/* Device interface class GUID we publish; the agent enumerates it. */
static const GUID DfyDeviceInterfaceGuid = DFY_VDISPLAY_DEVICE_INTERFACE_GUID;

/*
 * Single-adapter assumption for phase 1: see DFY_ADAPTER_CONTEXT / DfyCurrentDeviceContext
 * in driver.h.  The INF installs one root device, so this is never ambiguous today.
 */
static PDFY_DEVICE_CONTEXT g_DfyDeviceContext = NULL;

PDFY_DEVICE_CONTEXT DfyCurrentDeviceContext(void)
{
    return g_DfyDeviceContext;
}

/* Strings reported through IDDCX_ADAPTER_CAPS.EndPointDiagnostics (no allocation:
 * these must remain valid for the lifetime of the adapter). */
static const WCHAR DfyEndpointFriendlyName[]   = L"Dafeiyu Virtual Display";
static const WCHAR DfyEndpointManufacturer[]   = L"Dafeiyu";
static const WCHAR DfyEndpointModelName[]      = L"Dafeiyu VDisplay";

/* ========================================================================= */
/* Entry point                                                               */
/* ========================================================================= */

NTSTATUS DriverEntry(PDRIVER_OBJECT DriverObject, PUNICODE_STRING RegistryPath)
{
    WDF_DRIVER_CONFIG config;
    WDFDRIVER driver;
    NTSTATUS status;

    WPP_INIT_TRACING(DriverObject, RegistryPath);
    TraceEvents(TRACE_LEVEL_INFORMATION, TRACE_DRIVER, ("%!FUNC! entering"));

    WDF_DRIVER_CONFIG_INIT(&config, DfyEvtDeviceAdd);
    status = WdfDriverCreate(DriverObject, RegistryPath, WDF_NO_OBJECT_ATTRIBUTES, &config, &driver);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_ERROR, TRACE_DRIVER, ("%!FUNC! WdfDriverCreate failed 0x%08x", status));
    }

    WPP_CLEANUP(DriverObject);
    return status;
}

/* ========================================================================= */
/* Device add / power                                                        */
/* ========================================================================= */

NTSTATUS DfyEvtDeviceAdd(WDFDRIVER Driver, PWDFDEVICE_INIT DeviceInit)
{
    WDF_PNPPOWER_EVENT_CALLBACKS pnpPowerCallbacks;
    WDF_OBJECT_ATTRIBUTES attributes;
    WDF_WAITLOCK_CONFIG lockConfig;
    IDD_CX_CLIENT_CONFIG iddConfig;
    WDFDEVICE device;
    PDFY_DEVICE_CONTEXT ctx;
    NTSTATUS status;

    UNREFERENCED_PARAMETER(Driver);

    /* --- PnP/power callbacks.  IddCx requires adapter init to happen from D0Entry. */
    WDF_PNPPOWER_EVENT_CALLBACKS_INIT(&pnpPowerCallbacks);
    pnpPowerCallbacks.EvtDeviceD0Entry = DfyEvtDeviceD0Entry;
    pnpPowerCallbacks.EvtDeviceD0Exit  = DfyEvtDeviceD0Exit;
    WdfDeviceInitSetPnpPowerEventCallbacks(DeviceInit, &pnpPowerCallbacks);

    /* --- IddCx client configuration: every callback we implement.           */
    IDD_CX_CLIENT_CONFIG_INIT(&iddConfig);
    iddConfig.EvtIddCxDeviceIoControl = DfyEvtIddCxDeviceIoControl;
    iddConfig.EvtIddCxAdapterInitFinished = DfyEvtIddCxAdapterInitFinished;
    iddConfig.EvtIddCxParseMonitorDescription = DfyEvtIddCxParseMonitorDescription;
    iddConfig.EvtIddCxMonitorGetDefaultDescriptionModes = DfyEvtIddCxMonitorGetDefaultDescriptionModes;
    iddConfig.EvtIddCxMonitorQueryTargetModes = DfyEvtIddCxMonitorQueryTargetModes;
    iddConfig.EvtIddCxAdapterCommitModes = DfyEvtIddCxAdapterCommitModes;
    iddConfig.EvtIddCxMonitorAssignSwapChain = DfyEvtIddCxMonitorAssignSwapChain;
    iddConfig.EvtIddCxMonitorUnassignSwapChain = DfyEvtIddCxMonitorUnassignSwapChain;

    /*
     * IddCxDeviceInitConfig must run before WdfDeviceCreate: it rewrites the device
     * init structure so that IddCx owns the device queues, including
     * IRP_MJ_DEVICE_CONTROL (which is why our IOCTLs arrive at
     * EvtIddCxDeviceIoControl and not at EvtIoDeviceControl).
     */
    status = IddCxDeviceInitConfig(DeviceInit, &iddConfig);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_ERROR, TRACE_DRIVER, ("%!FUNC! IddCxDeviceInitConfig 0x%08x", status));
        return status;
    }

    WDF_OBJECT_ATTRIBUTES_INIT_CONTEXT_TYPE(&attributes, DFY_DEVICE_CONTEXT);
    attributes.EvtCleanupCallback = DfyEvtDeviceCleanup;

    status = WdfDeviceCreate(&DeviceInit, &attributes, &device);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_ERROR, TRACE_DRIVER, ("%!FUNC! WdfDeviceCreate 0x%08x", status));
        return status;
    }

    status = IddCxDeviceInitialize(device);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_ERROR, TRACE_DRIVER, ("%!FUNC! IddCxDeviceInitialize 0x%08x", status));
        return status;
    }

    ctx = DfyGetDeviceContext(device);
    ctx->WdfDevice = device;
    g_DfyDeviceContext = ctx;

    WDF_WAITLOCK_CONFIG_INIT(&lockConfig, WDF_NO_OBJECT_ATTRIBUTES);
    status = WdfWaitLockCreate(&lockConfig, &ctx->StateLock);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_ERROR, TRACE_DRIVER, ("%!FUNC! WdfWaitLockCreate 0x%08x", status));
        return status;
    }

    /*
     * Auto-reset event the agent waits on for hotplug/mode-change notifications.
     * Failure is not fatal: the agent also polls LIST, and it opens the event itself,
     * so a NULL handle here only means "no push notifications".
     */
    ctx->DeviceEvent = CreateEventW(NULL, FALSE, FALSE, DFY_VDISPLAY_EVENT_NAME);
    if (ctx->DeviceEvent == NULL) {
        TraceEvents(TRACE_LEVEL_WARNING, TRACE_DRIVER,
                    ("%!FUNC! CreateEventW(%ws) failed %lu; hotplug will not be signalled",
                     DFY_VDISPLAY_EVENT_NAME, GetLastError()));
    }

    /*
     * Publish the device interface class id {54EC77FA-...}.  The device instance path
     * also carries our root enumerator id, so the agent can tell our interface from
     * another indirect-display driver's interface on the same machine.
     */
    status = WdfDeviceCreateDeviceInterface(device, &DfyDeviceInterfaceGuid, NULL);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_ERROR, TRACE_DRIVER,
                    ("%!FUNC! WdfDeviceCreateDeviceInterface 0x%08x", status));
        return status;
    }

    TraceEvents(TRACE_LEVEL_INFORMATION, TRACE_DRIVER, ("%!FUNC! device ready"));
    return STATUS_SUCCESS;
}

NTSTATUS DfyEvtDeviceD0Entry(WDFDEVICE Device, WDF_POWER_DEVICE_STATE PreviousState)
{
    PDFY_DEVICE_CONTEXT ctx = DfyGetDeviceContext(Device);

    UNREFERENCED_PARAMETER(PreviousState);

    /*
     * The adapter is initialized asynchronously; the OS calls back
     * DfyEvtIddCxAdapterInitFinished when that finished.  A second D0 entry after a
     * sleep/wake cycle must not create a second adapter.
     */
    if (ctx->Adapter != NULL) {
        return STATUS_SUCCESS;
    }
    return DfyInitAdapter(ctx);
}

NTSTATUS DfyEvtDeviceD0Exit(WDFDEVICE Device, WDF_POWER_DEVICE_STATE TargetState)
{
    PDFY_DEVICE_CONTEXT ctx = DfyGetDeviceContext(Device);
    UINT32 i;

    UNREFERENCED_PARAMETER(TargetState);

    /*
     * The OS unassigns swap chains before D0 exit, but a worker that fails to observe
     * its terminate event is the classic DRIVER_POWER_STATE_FAILURE.  Stop them here,
     * synchronously, before the device goes down.
     */
    for (i = 0; i < DFY_VDISPLAY_MAX_MONITORS; i++) {
        DfyStopSwapChainWorker(&ctx->Slots[i]);
    }
    return STATUS_SUCCESS;
}

VOID DfyEvtDeviceCleanup(WDFOBJECT Device)
{
    PDFY_DEVICE_CONTEXT ctx = DfyGetDeviceContext((WDFDEVICE)Device);
    UINT32 i;

    for (i = 0; i < DFY_VDISPLAY_MAX_MONITORS; i++) {
        DfyStopSwapChainWorker(&ctx->Slots[i]);
    }
    if (ctx->DeviceEvent != NULL) {
        CloseHandle(ctx->DeviceEvent);
        ctx->DeviceEvent = NULL;
    }
    if (g_DfyDeviceContext == ctx) {
        g_DfyDeviceContext = NULL;
    }
}

/* ========================================================================= */
/* Adapter initialization                                                    */
/* ========================================================================= */

NTSTATUS DfyInitAdapter(PDFY_DEVICE_CONTEXT ctx)
{
    IDDCX_ADAPTER_CAPS caps;
    IDARG_IN_ADAPTER_INIT adapterInit;
    IDARG_OUT_ADAPTER_INIT adapterInitOut;
    WDF_OBJECT_ATTRIBUTES attributes;
    PDFY_ADAPTER_CONTEXT adapterContext;
    NTSTATUS status;

    RtlZeroMemory(&caps, sizeof(caps));
    caps.Size = sizeof(caps);
    caps.MaxMonitorsSupported = DFY_VDISPLAY_MAX_MONITORS;

    caps.EndPointDiagnostics.Size = sizeof(caps.EndPointDiagnostics);
    caps.EndPointDiagnostics.GammaSupport = IDDCX_FEATURE_IMPLEMENTATION_NONE;
    caps.EndPointDiagnostics.TransmissionType = IDDCX_TRANSMISSION_TYPE_WIRED_OTHER;
    caps.EndPointDiagnostics.pEndPointFriendlyName = DfyEndpointFriendlyName;
    caps.EndPointDiagnostics.pEndPointManufacturerName = DfyEndpointManufacturer;
    caps.EndPointDiagnostics.pEndPointModelName = DfyEndpointModelName;

    /*
     * The adapter object is a WDF object created by IddCx; the only way to get back to
     * our device context from EvtIddCxAdapterInitFinished is a context we attach here.
     */
    WDF_OBJECT_ATTRIBUTES_INIT_CONTEXT_TYPE(&attributes, DFY_ADAPTER_CONTEXT);

    RtlZeroMemory(&adapterInit, sizeof(adapterInit));
    adapterInit.Size = sizeof(adapterInit);
    adapterInit.WdfDevice = ctx->WdfDevice;
    adapterInit.pCaps = &caps;
    adapterInit.ObjectAttributes = &attributes;

    status = IddCxAdapterInitAsync(&adapterInit, &adapterInitOut);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_ERROR, TRACE_DRIVER, ("%!FUNC! IddCxAdapterInitAsync 0x%08x", status));
        return status;
    }

    adapterContext = DfyGetAdapterContext((WDFOBJECT)adapterInitOut.AdapterObject);
    adapterContext->DeviceContext = ctx;
    return STATUS_SUCCESS;
}

NTSTATUS DfyEvtIddCxAdapterInitFinished(IDDCX_ADAPTER AdapterObject,
                                        const IDARG_IN_ADAPTER_INIT_FINISHED *pInArgs)
{
    PDFY_ADAPTER_CONTEXT adapterContext = DfyGetAdapterContext((WDFOBJECT)AdapterObject);
    PDFY_DEVICE_CONTEXT ctx = adapterContext->DeviceContext;
    NTSTATUS status = STATUS_SUCCESS;
    UINT32 i;

    UNREFERENCED_PARAMETER(pInArgs);

    if (ctx == NULL) {
        /* Cannot happen unless the descriptor above is wrong; fail loudly but safely. */
        return STATUS_INTERNAL_ERROR;
    }

    WdfWaitLockAcquire(ctx->StateLock, NULL);
    ctx->Adapter = AdapterObject;
    ctx->AdapterReady = TRUE;

    /*
     * CREATE can only succeed once the adapter exists.  A create request that raced the
     * async init is not possible from the agent (it cannot open the interface before the
     * device starts), but a reboot with a stale agent can.  Attach any slot that was
     * claimed while the adapter was still initializing.
     */
    for (i = 0; i < DFY_VDISPLAY_MAX_MONITORS; i++) {
        if (ctx->Slots[i].Used && !ctx->Slots[i].Arrived) {
            NTSTATUS createStatus = DfyCreateMonitor(ctx, i);
            if (!NT_SUCCESS(createStatus)) {
                status = createStatus;
            }
        }
    }
    WdfWaitLockRelease(ctx->StateLock);

    TraceEvents(TRACE_LEVEL_INFORMATION, TRACE_DRIVER, ("%!FUNC! adapter ready status=0x%08x", status));
    return status;
}

/* ========================================================================= */
/* Control plane: IOCTLs                                                     */
/* ========================================================================= */

NTSTATUS DfyEvtIddCxDeviceIoControl(WDFDEVICE Device, WDFREQUEST Request,
                                    size_t OutputBufferLength, size_t InputBufferLength,
                                    ULONG IoControlCode)
{
    PDFY_DEVICE_CONTEXT ctx = DfyGetDeviceContext(Device);

    /*
     * Every handler below completes the request, including on error.  We stay
     * synchronous on purpose: all six control operations are microsecond-scale and
     * must not leave a request pending while the device tears down.
     */
    switch (IoControlCode) {
    case IOCTL_VDISPLAY_CREATE:
        DfyHandleIoctlCreate(ctx, Request, InputBufferLength, OutputBufferLength);
        break;
    case IOCTL_VDISPLAY_UPDATE:
        DfyHandleIoctlUpdate(ctx, Request, InputBufferLength);
        break;
    case IOCTL_VDISPLAY_DESTROY:
        DfyHandleIoctlDestroy(ctx, Request, InputBufferLength);
        break;
    case IOCTL_VDISPLAY_LIST:
        DfyHandleIoctlList(ctx, Request, OutputBufferLength);
        break;
    case IOCTL_VDISPLAY_TAKE_EVENT:
        DfyHandleIoctlTakeEvent(ctx, Request, OutputBufferLength);
        break;
    case IOCTL_VDISPLAY_GET_PROTOCOL_INFO:
        DfyHandleIoctlGetProtocolInfo(ctx, Request, OutputBufferLength);
        break;
    default:
        DfyCompleteRequest(Request, STATUS_INVALID_DEVICE_REQUEST, 0);
        return STATUS_INVALID_DEVICE_REQUEST;
    }

    return STATUS_SUCCESS;
}

VOID DfyCompleteRequest(WDFREQUEST Request, NTSTATUS Status, size_t Information)
{
    WdfRequestCompleteWithInformation(Request, Status, Information);
}

static NTSTATUS DfyRetrieveInput(WDFREQUEST Request, size_t Required, PVOID *Buffer)
{
    NTSTATUS status;
    size_t length = 0;

    status = WdfRequestRetrieveInputBuffer(Request, Required, Buffer, &length);
    if (!NT_SUCCESS(status)) {
        return status;
    }
    if (length < Required) {
        return STATUS_BUFFER_TOO_SMALL;
    }
    return STATUS_SUCCESS;
}

static NTSTATUS DfyRetrieveOutput(WDFREQUEST Request, size_t Required, PVOID *Buffer)
{
    NTSTATUS status;
    size_t length = 0;

    status = WdfRequestRetrieveOutputBuffer(Request, Required, Buffer, &length);
    if (!NT_SUCCESS(status)) {
        return status;
    }
    if (length < Required) {
        return STATUS_BUFFER_TOO_SMALL;
    }
    return STATUS_SUCCESS;
}

NTSTATUS DfyValidateMode(UINT32 Width, UINT32 Height, UINT32 RefreshHz, UINT32 Dpi)
{
    /* Keep in sync with src/lib.rs: MIN_DIMENSION..=MAX_DIMENSION and the other ranges. */
    if (Width < 16 || Width > 16384 || Height < 16 || Height > 16384) {
        return STATUS_INVALID_PARAMETER;
    }
    if ((Width % 2) != 0 || (Height % 2) != 0) {
        return STATUS_INVALID_PARAMETER;
    }
    if (RefreshHz < 1 || RefreshHz > 360) {
        return STATUS_INVALID_PARAMETER;
    }
    if (Dpi < 24 || Dpi > 480) {
        return STATUS_INVALID_PARAMETER;
    }
    return STATUS_SUCCESS;
}

VOID DfyHandleIoctlCreate(PDFY_DEVICE_CONTEXT ctx, WDFREQUEST Request,
                          size_t InputLength, size_t OutputLength)
{
    PDFY_VDISPLAY_CREATE input = NULL;
    UINT32 *output = NULL;
    UINT32 id = DFY_VDISPLAY_INVALID_ID;
    UINT32 i;
    NTSTATUS status;

    UNREFERENCED_PARAMETER(InputLength);

    status = DfyRetrieveInput(Request, sizeof(DFY_VDISPLAY_CREATE), (PVOID *)&input);
    if (!NT_SUCCESS(status)) {
        DfyCompleteRequest(Request, status, 0);
        return;
    }
    status = DfyRetrieveOutput(Request, sizeof(UINT32), (PVOID *)&output);
    if (!NT_SUCCESS(status)) {
        DfyCompleteRequest(Request, status, 0);
        return;
    }

    status = DfyValidateMode(input->Width, input->Height, input->RefreshHz, input->Dpi);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_WARNING, TRACE_CONTROL,
                    ("%!FUNC! rejected mode %ux%u@%u dpi=%u", input->Width, input->Height,
                     input->RefreshHz, input->Dpi));
        DfyCompleteRequest(Request, status, 0);
        return;
    }

    WdfWaitLockAcquire(ctx->StateLock, NULL);

    if (!ctx->AdapterReady) {
        WdfWaitLockRelease(ctx->StateLock);
        DfyCompleteRequest(Request, STATUS_DEVICE_NOT_READY, 0);
        return;
    }

    for (i = 0; i < DFY_VDISPLAY_MAX_MONITORS; i++) {
        if (!ctx->Slots[i].Used) {
            break;
        }
    }
    if (i == DFY_VDISPLAY_MAX_MONITORS) {
        WdfWaitLockRelease(ctx->StateLock);
        TraceEvents(TRACE_LEVEL_WARNING, TRACE_CONTROL, ("%!FUNC! all %u connectors in use",
                                                         DFY_VDISPLAY_MAX_MONITORS));
        DfyCompleteRequest(Request, STATUS_INSUFFICIENT_RESOURCES, 0);
        return;
    }

    /*
     * The display id we hand to the agent is the connector index: it is stable for the
     * lifetime of the device, survives driver reload, and is what the OS reports in
     * every monitor callback, which keeps the mapping trivial in both directions.
     */
    RtlZeroMemory(&ctx->Slots[i], sizeof(ctx->Slots[i]));
    ctx->Slots[i].Used = TRUE;
    ctx->Slots[i].DisplayId = i;
    ctx->Slots[i].Current.Width = input->Width;
    ctx->Slots[i].Current.Height = input->Height;
    ctx->Slots[i].Current.RefreshHz = input->RefreshHz;
    ctx->Slots[i].Current.Dpi = input->Dpi;
    RtlCopyMemory(ctx->Slots[i].NameHint, input->NameHint, DFY_VDISPLAY_NAME_MAX);
    DfyBuildModeTable(&ctx->Slots[i]);
    DfyBuildEdid(&ctx->Slots[i].Current, ctx->Slots[i].NameHint, ctx->Slots[i].Edid,
                 &ctx->Slots[i].EdidSize);

    status = DfyCreateMonitor(ctx, i);
    if (NT_SUCCESS(status)) {
        id = i;
    } else {
        RtlZeroMemory(&ctx->Slots[i], sizeof(ctx->Slots[i]));
    }

    WdfWaitLockRelease(ctx->StateLock);

    if (!NT_SUCCESS(status)) {
        DfyCompleteRequest(Request, status, 0);
        return;
    }

    *output = id;
    DfyCompleteRequest(Request, STATUS_SUCCESS, sizeof(UINT32));
    TraceEvents(TRACE_LEVEL_INFORMATION, TRACE_CONTROL, ("%!FUNC! created id=%u", id));
}

VOID DfyHandleIoctlUpdate(PDFY_DEVICE_CONTEXT ctx, WDFREQUEST Request, size_t InputLength)
{
    PDFY_VDISPLAY_UPDATE input = NULL;
    PDFY_DISPLAY_SLOT slot;
    NTSTATUS status;

    UNREFERENCED_PARAMETER(InputLength);

    status = DfyRetrieveInput(Request, sizeof(DFY_VDISPLAY_UPDATE), (PVOID *)&input);
    if (!NT_SUCCESS(status)) {
        DfyCompleteRequest(Request, status, 0);
        return;
    }
    status = DfyValidateMode(input->Width, input->Height, input->RefreshHz, input->Dpi);
    if (!NT_SUCCESS(status)) {
        DfyCompleteRequest(Request, status, 0);
        return;
    }

    WdfWaitLockAcquire(ctx->StateLock, NULL);
    slot = DfyFindSlotById(ctx, input->Id);
    if (slot == NULL) {
        WdfWaitLockRelease(ctx->StateLock);
        DfyCompleteRequest(Request, STATUS_INVALID_PARAMETER, 0);
        return;
    }

    slot->Current.Width = input->Width;
    slot->Current.Height = input->Height;
    slot->Current.RefreshHz = input->RefreshHz;
    slot->Current.Dpi = input->Dpi;
    DfyBuildModeTable(slot);
    DfyPushEventLocked(ctx, DFY_EVENT_MODES_CHANGED, slot->DisplayId);

    /*
     * Push the new table to the OS.  This is IddCx 1.2's API: the agent's remote
     * resolution change ends up here, the OS re-queries the mode table and re-commits
     * the *virtual* monitor only.  No physical output is touched because the physical
     * paths are not in this adapter's target list.
     *
     * V2 (IddCx 1.10 / Win11 22H2 Sept+): IddCxMonitorUpdateModes2 with
     * IDARG_IN_UPDATEMODES2 and IDDCX_TARGET_MODE2 for HDR-capable modes.  Cannot be
     * called from this package because it declares UmdfExtensions=IddCx0102.
     */
    if (slot->Arrived) {
        IDARG_IN_UPDATEMODES update;
        IDDCX_TARGET_MODE targetModes[DFY_VDISPLAY_MAX_MODES];
        UINT32 m;

        for (m = 0; m < slot->ModeCount; m++) {
            targetModes[m] = DfyMakeTargetMode(&slot->Modes[m]);
        }
        RtlZeroMemory(&update, sizeof(update));
        update.Size = sizeof(update);
        update.Reason = IDDCX_UPDATE_REASON_OTHER; /* TODO: check IDDCX_UPDATE_REASON enum */
        update.TargetModeCount = slot->ModeCount;
        update.pTargetModes = targetModes;

        status = IddCxMonitorUpdateModes(slot->Monitor, &update);
        if (!NT_SUCCESS(status)) {
            TraceEvents(TRACE_LEVEL_WARNING, TRACE_CONTROL,
                        ("%!FUNC! IddCxMonitorUpdateModes(connector %u) 0x%08x", slot->DisplayId,
                         status));
        }
    }
    WdfWaitLockRelease(ctx->StateLock);

    if (NT_SUCCESS(status)) {
        DfyCompleteRequest(Request, STATUS_SUCCESS, 0);
        TraceEvents(TRACE_LEVEL_INFORMATION, TRACE_CONTROL,
                    ("%!FUNC! updated id=%u to %ux%u@%u", input->Id, input->Width, input->Height,
                     input->RefreshHz));
    } else {
        DfyCompleteRequest(Request, status, 0);
    }
}

VOID DfyHandleIoctlDestroy(PDFY_DEVICE_CONTEXT ctx, WDFREQUEST Request, size_t InputLength)
{
    PDFY_VDISPLAY_DESTROY input = NULL;
    PDFY_DISPLAY_SLOT slot;
    NTSTATUS status;

    UNREFERENCED_PARAMETER(InputLength);

    status = DfyRetrieveInput(Request, sizeof(DFY_VDISPLAY_DESTROY), (PVOID *)&input);
    if (!NT_SUCCESS(status)) {
        DfyCompleteRequest(Request, status, 0);
        return;
    }

    WdfWaitLockAcquire(ctx->StateLock, NULL);
    slot = DfyFindSlotById(ctx, input->Id);
    if (slot == NULL) {
        WdfWaitLockRelease(ctx->StateLock);
        DfyCompleteRequest(Request, STATUS_INVALID_PARAMETER, 0);
        return;
    }

    /*
     * Full teardown of one virtual display: stop its swap-chain worker, withdraw the
     * monitor (the OS then removes that display's paths), free the connector slot.
     * The text-mode friendly name and EDID are re-created on the next CREATE.
     */
    DfyStopSwapChainWorker(slot);
    DfyDestroyMonitor(ctx, input->Id);
    RtlZeroMemory(slot, sizeof(*slot));
    WdfWaitLockRelease(ctx->StateLock);

    DfyCompleteRequest(Request, STATUS_SUCCESS, 0);
    TraceEvents(TRACE_LEVEL_INFORMATION, TRACE_CONTROL, ("%!FUNC! destroyed id=%u", input->Id));
}

VOID DfyHandleIoctlList(PDFY_DEVICE_CONTEXT ctx, WDFREQUEST Request, size_t OutputLength)
{
    PDFY_VDISPLAY_STATE_LIST out = NULL;
    UINT32 i;
    NTSTATUS status;

    UNREFERENCED_PARAMETER(OutputLength);

    status = DfyRetrieveOutput(Request, sizeof(DFY_VDISPLAY_STATE_LIST), (PVOID *)&out);
    if (!NT_SUCCESS(status)) {
        DfyCompleteRequest(Request, status, 0);
        return;
    }
    RtlZeroMemory(out, sizeof(*out));

    WdfWaitLockAcquire(ctx->StateLock, NULL);
    for (i = 0; i < DFY_VDISPLAY_MAX_MONITORS; i++) {
        const DFY_DISPLAY_SLOT *slot = &ctx->Slots[i];
        PDFY_VDISPLAY_STATE state;

        if (!slot->Used) {
            continue;
        }
        state = &out->States[out->Header.Count];
        state->Id = slot->DisplayId;
        state->Width = slot->Current.Width;
        state->Height = slot->Current.Height;
        state->RefreshHz = slot->Current.RefreshHz;
        state->Dpi = slot->Current.Dpi;
        state->Attached = slot->Arrived ? 1u : 0u;
        out->Header.Count++;
    }
    WdfWaitLockRelease(ctx->StateLock);

    DfyCompleteRequest(Request, STATUS_SUCCESS, sizeof(DFY_VDISPLAY_STATE_LIST));
}

VOID DfyHandleIoctlTakeEvent(PDFY_DEVICE_CONTEXT ctx, WDFREQUEST Request, size_t OutputLength)
{
    PDFY_VDISPLAY_EVENT out = NULL;
    NTSTATUS status;

    UNREFERENCED_PARAMETER(OutputLength);

    status = DfyRetrieveOutput(Request, sizeof(DFY_VDISPLAY_EVENT), (PVOID *)&out);
    if (!NT_SUCCESS(status)) {
        DfyCompleteRequest(Request, status, 0);
        return;
    }

    WdfWaitLockAcquire(ctx->StateLock, NULL);
    if (ctx->EventCount == 0) {
        WdfWaitLockRelease(ctx->StateLock);
        /* No event pending is a successful call with zero information bytes. */
        DfyCompleteRequest(Request, STATUS_SUCCESS, 0);
        return;
    }

    {
        UINT32 tail = (ctx->EventHead + DFY_VDISPLAY_MAX_PENDING_EVENTS - ctx->EventCount) %
                      DFY_VDISPLAY_MAX_PENDING_EVENTS;
        *out = ctx->EventRing[tail];
        ctx->EventCount--;
    }
    WdfWaitLockRelease(ctx->StateLock);

    DfyCompleteRequest(Request, STATUS_SUCCESS, sizeof(DFY_VDISPLAY_EVENT));
}

