/*
 * The table the agent asked for, plus the OS-mandated fallbacks a monitor may need
 * during boot or a driver reload (a display with only one mode is fragile: the OS may
 * refuse a topology where no listed mode matches the desktop).  Keep the smallest set
 * that is still safe.
 */
void DfyBuildModeTable(PDFY_DISPLAY_SLOT slot)
{
    UINT32 count = 0;
    const DFY_MODE fallbacks[] = {
        { 1024, 768, 60, 96 },
        { 1280, 720, 60, 96 },
        { 1920, 1080, 60, 96 },
        { 2560, 1440, 60, 96 },
    };
    UINT32 i;

    slot->Modes[count++] = slot->Current;

    for (i = 0; i < RTL_NUMBER_OF(fallbacks) && count < DFY_VDISPLAY_MAX_MODES; i++) {
        UINT32 j;
        BOOLEAN duplicate = FALSE;
        for (j = 0; j < count; j++) {
            if (slot->Modes[j].Width == fallbacks[i].Width &&
                slot->Modes[j].Height == fallbacks[i].Height &&
                slot->Modes[j].RefreshHz == fallbacks[i].RefreshHz) {
                duplicate = TRUE;
                break;
            }
        }
        if (!duplicate) {
            slot->Modes[count++] = fallbacks[i];
        }
    }
    slot->ModeCount = count;
}

/*
 * Build a 128-byte EDID 1.3 base block: identity only.  The authoritative mode list
 * is *not* the EDID (that is what IDDCX_MONITOR_QUERY_TARGET_MODES and
 * IddCxMonitorUpdateModes are for); the EDID exists so the monitor has a stable
 * identity, a preferred timing and a name Windows can show.
 *
 * TODO(phase-1b): validate the generated block with `edid-decode` and with a real
 * Windows 10/11 install before trusting it; the preferred timing math below is a
 * placeholder and must be replaced by a CVT/DMT-consistent computation.
 */
void DfyBuildEdid(const DFY_MODE *Mode, const UINT8 *NameHint, UINT8 *Edid, UINT32 *EdidSize)
{
    static const UINT8 header[8] = { 0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00 };
    UINT32 width = Mode->Width;
    UINT32 height = Mode->Height;
    UINT32 refresh = Mode->RefreshHz == 0 ? 60 : Mode->RefreshHz;
    UINT32 hBlank, vBlank;
    UINT32 pixelClock10kHz;
    UINT8 checksum = 0;
    UINT32 i;

    RtlZeroMemory(Edid, 128);

    /* Header + vendor/product identification. */
    RtlCopyMemory(Edid, header, sizeof(header));
    Edid[8] = 0x3A;                     /* manufacturer id, three 5-bit letters ("DFY" placeholder) */
    Edid[9] = 0x2D;
    Edid[10] = 0x01;                    /* product code, little endian */
    Edid[11] = 0x00;
    Edid[12] = 0x01;                    /* serial number */
    Edid[13] = 0x00;
    Edid[16] = 0x1B;                    /* week 27 */
    Edid[17] = 0x21;                    /* year 2025 - 1990 = 33 (0x21) */

    /* EDID 1.3 base block. */
    Edid[18] = 0x01;
    Edid[19] = 0x03;
    Edid[20] = 0x80;                    /* digital input, 8 bits per primary colour */
    Edid[21] = (UINT8)((width - 1) & 0xFF);
    Edid[22] = (UINT8)((height - 1) & 0xFF);
    Edid[23] = 0x78;                    /* gamma 2.2 */
    Edid[24] = 0x0A;                    /* RGB 4:4:4 + YCbCr 4:4:4 */

    /* Chromaticity coordinates: sRGB D65 approximations (valid for a virtual panel). */
    Edid[25] = 0xEE; Edid[26] = 0x91; Edid[27] = 0xA3; Edid[28] = 0x54;
    Edid[29] = 0x4C; Edid[30] = 0x99; Edid[31] = 0x26; Edid[32] = 0x0F;
    Edid[33] = 0x50; Edid[34] = 0x54;

    /* Established timings: 640x480@60 only; everything else is in the mode table. */
    Edid[35] = 0x21;
    Edid[36] = 0x00;
    Edid[37] = 0x00;

    /* Standard timings (bytes 38..53): unused. */
    for (i = 38; i < 54; i++) {
        Edid[i] = 0x01;
    }

    /*
     * Preferred detailed timing descriptor.  Total blanking is derived from the CVT
     * minimum blanking (160 pixels / 3 lines) and rounded to the EDID field widths;
     * the sync offsets/widths are the common 8/40 horizontal and 3/6 vertical values.
     */
    hBlank = (width / 4) + 160;
    vBlank = 3 + (height / 20);
    pixelClock10kHz = ((width + hBlank) * (height + vBlank) * refresh) / 10000;
    if (pixelClock10kHz > 0xFFFF) {
        pixelClock10kHz = 0xFFFF;
    }

    Edid[54] = (UINT8)(pixelClock10kHz & 0xFF);
    Edid[55] = (UINT8)((pixelClock10kHz >> 8) & 0xFF);
    Edid[56] = (UINT8)(width & 0xFF);
    Edid[57] = (UINT8)(hBlank & 0xFF);
    Edid[58] = (UINT8)(((width >> 8) & 0x0F) << 4 | ((hBlank >> 8) & 0x0F));
    Edid[59] = (UINT8)(height & 0xFF);
    Edid[60] = (UINT8)(vBlank & 0xFF);
    Edid[61] = (UINT8)(((height >> 8) & 0x0F) << 4 | ((vBlank >> 8) & 0x0F));
    Edid[62] = 0x08;                    /* h sync offset */
    Edid[63] = 0x28;                    /* h sync pulse width */
    Edid[64] = 0x03;                    /* v sync offset << 4 | v sync pulse width */
    Edid[65] = 0x00;
    Edid[66] = 0x00;
    Edid[67] = 0x00;
    Edid[68] = 0x00;
    Edid[69] = 0x00;                    /* no borders, no stereo */
    Edid[71] = 0x1E;                    /* non-interlaced, digital separate sync, +H/+V */

    /* Descriptor 2: monitor name.  \0 \0 \0 \xFC \0 then 13 characters (padded). */
    Edid[72] = 0x00; Edid[73] = 0x00; Edid[74] = 0x00; Edid[75] = 0xFC; Edid[76] = 0x00;
    for (i = 0; i < 13; i++) {
        UINT8 ch = 0x0A;                /* newline terminates the string */
        if (NameHint != NULL && NameHint[i] != 0) {
            ch = NameHint[i] >= 0x20 && NameHint[i] < 0x7F ? NameHint[i] : '?';
        }
        Edid[77 + i] = ch;
    }

    /* Descriptor 3, 4: unused descriptors. */
    Edid[90] = 0x00; Edid[91] = 0x00; Edid[92] = 0x00; Edid[93] = 0x10; Edid[94] = 0x00;
    Edid[108] = 0x00; Edid[109] = 0x00; Edid[110] = 0x00; Edid[111] = 0x10; Edid[112] = 0x00;

    Edid[126] = 0x00;                   /* no extension blocks */

    for (i = 0; i < 127; i++) {
        checksum = (UINT8)(checksum + Edid[i]);
    }
    Edid[127] = (UINT8)(0x100 - checksum);

    *EdidSize = 128;
}

IDDCX_TARGET_MODE DfyMakeTargetMode(const DFY_MODE *Mode)
{
    IDDCX_TARGET_MODE target;
    const UINT32 width = Mode->Width;
    const UINT32 height = Mode->Height;
    const UINT32 refresh = Mode->RefreshHz == 0 ? 60 : Mode->RefreshHz;

    RtlZeroMemory(&target, sizeof(target));
    target.Size = sizeof(target);

    /*
     * TODO(phase-1b): this is the IDDCX_TARGET_MODE shape from iddcx.h (Win10 1809+).
     * FillSignalInfo-style math must agree with the EDID detailed timing and with
     * what the OS computes, otherwise Windows marks the mode as unsupported.  Field
     * names to re-verify: TargetVideoSignalInfo.{activeSize,totalSize,pixelRate,
     * hSyncFreq,vSyncFreq,scanLineOrdering}.
     */
    target.TargetVideoSignalInfo.activeSize.cx = width;
    target.TargetVideoSignalInfo.activeSize.cy = height;
    target.TargetVideoSignalInfo.totalSize.cx = width + (width / 4) + 160;
    target.TargetVideoSignalInfo.totalSize.cy = height + 3 + (height / 20);
    target.TargetVideoSignalInfo.pixelRate =
        target.TargetVideoSignalInfo.totalSize.cx * target.TargetVideoSignalInfo.totalSize.cy * refresh;
    target.TargetVideoSignalInfo.vSyncFreq.Numerator = refresh;
    target.TargetVideoSignalInfo.vSyncFreq.Denominator = 1;
    target.TargetVideoSignalInfo.hSyncFreq.Numerator =
        refresh * target.TargetVideoSignalInfo.totalSize.cy;
    target.TargetVideoSignalInfo.hSyncFreq.Denominator = 1;
    target.TargetVideoSignalInfo.scanLineOrdering = DISPLAYCONFIG_SCANLINE_ORDERING_PROGRESSIVE;
    return target;
}

