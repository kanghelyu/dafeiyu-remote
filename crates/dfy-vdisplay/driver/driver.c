void DfyPushEventLocked(PDFY_DEVICE_CONTEXT ctx, UINT32 Kind, UINT32 Id)
{
    if (ctx->EventCount == DFY_VDISPLAY_MAX_PENDING_EVENTS) {
        /* Drop the oldest: the ring may not grow, and a missed hotplug is recoverable
         * via LIST, while dropping the newest would hide the just-happened change. */
        UINT32 tail = (ctx->EventHead + DFY_VDISPLAY_MAX_PENDING_EVENTS - ctx->EventCount) %
                      DFY_VDISPLAY_MAX_PENDING_EVENTS;
        ctx->EventRing[tail].Kind = 0;
        ctx->EventRing[tail].Id = 0;
        ctx->EventCount--;
    }
    ctx->EventRing[ctx->EventHead].Kind = Kind;
    ctx->EventRing[ctx->EventHead].Id = Id;
    ctx->EventHead = (ctx->EventHead + 1) % DFY_VDISPLAY_MAX_PENDING_EVENTS;
    ctx->EventCount++;

    if (ctx->DeviceEvent != NULL) {
        SetEvent(ctx->DeviceEvent);
    }
}