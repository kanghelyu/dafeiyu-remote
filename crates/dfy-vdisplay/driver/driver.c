NTSTATUS DfyCreateMonitor(PDFY_DEVICE_CONTEXT ctx, UINT32 ConnectorIndex)
{
    PDFY_DISPLAY_SLOT slot = &ctx->Slots[ConnectorIndex];
    IDARG_IN_MONITORCREATE monitorCreate;
    IDARG_OUT_MONITORCREATE monitorCreateOut;
    IDARG_OUT_MONITORARRIVAL monitorArrivalOut;
    IDDCX_MONITOR_INFO monitorInfo;
    GUID containerId;
    NTSTATUS status;
    HRESULT hr;

    if (slot->Arrived) {
        return STATUS_SUCCESS;
    }

    /*
     * Container id groups the monitor with a physical "container" when one exists.
     * We generate a fresh GUID per virtual monitor so Windows treats each virtual
     * display as its own device (independent scaling/topology, removal does not
     * disturb another virtual display).
     */
    hr = CoCreateGuid(&containerId);
    if (FAILED(hr)) {
        return STATUS_UNSUCCESSFUL;
    }

    RtlZeroMemory(&monitorInfo, sizeof(monitorInfo));
    monitorInfo.Size = sizeof(monitorInfo);
    monitorInfo.MonitorType = DISPLAYCONFIG_OUTPUT_TECHNOLOGY_HDMI;
    monitorInfo.ConnectorIndex = ConnectorIndex;
    monitorInfo.MonitorDescription.Size = sizeof(monitorInfo.MonitorDescription);
    monitorInfo.MonitorDescription.Type = IDDCX_MONITOR_DESCRIPTION_TYPE_EDID;
    monitorInfo.MonitorDescription.DataSize = slot->EdidSize;
    monitorInfo.MonitorDescription.pData = slot->Edid;
    monitorInfo.MonitorContainerId = containerId;

    RtlZeroMemory(&monitorCreate, sizeof(monitorCreate));
    monitorCreate.Size = sizeof(monitorCreate);
    monitorCreate.MonitorInfo = monitorInfo;

    status = IddCxMonitorCreate(ctx->Adapter, &monitorCreate, &monitorCreateOut);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_ERROR, TRACE_MONITOR,
                    ("%!FUNC! IddCxMonitorCreate(connector %u) 0x%08x", ConnectorIndex, status));
        return status;
    }
    slot->Monitor = monitorCreateOut.MonitorObject;

    /*
     * Arrival/departure take only OUT args in the 1.2 DDI (verify against iddcx.h on
     * first build: the sample-era signatures are easy to get wrong).
     */
    RtlZeroMemory(&monitorArrivalOut, sizeof(monitorArrivalOut));
    status = IddCxMonitorArrival(slot->Monitor, &monitorArrivalOut);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_ERROR, TRACE_MONITOR,
                    ("%!FUNC! IddCxMonitorArrival(connector %u) 0x%08x", ConnectorIndex, status));
        WdfObjectDelete((WDFOBJECT)slot->Monitor);
        slot->Monitor = NULL;
        return status;
    }

    slot->Arrived = TRUE;
    DfyPushEventLocked(ctx, DFY_EVENT_MONITOR_ARRIVAL, slot->DisplayId);

    TraceEvents(TRACE_LEVEL_INFORMATION, TRACE_MONITOR, ("%!FUNC! monitor %u arrived", ConnectorIndex));
    return STATUS_SUCCESS;
}

void DfyDestroyMonitor(PDFY_DEVICE_CONTEXT ctx, UINT32 ConnectorIndex)
{
    PDFY_DISPLAY_SLOT slot = &ctx->Slots[ConnectorIndex];
    IDARG_OUT_MONITORDEPARTURE departureOut;
    NTSTATUS status;

    if (!slot->Arrived || slot->Monitor == NULL) {
        return;
    }

    RtlZeroMemory(&departureOut, sizeof(departureOut));
    status = IddCxMonitorDeparture(slot->Monitor, &departureOut);
    if (!NT_SUCCESS(status)) {
        TraceEvents(TRACE_LEVEL_WARNING, TRACE_MONITOR,
                    ("%!FUNC! IddCxMonitorDeparture(connector %u) 0x%08x", ConnectorIndex, status));
    }

    slot->Monitor = NULL;
    slot->Arrived = FALSE;
    DfyPushEventLocked(ctx, DFY_EVENT_MONITOR_DEPARTURE, slot->DisplayId);
}

